#!/usr/bin/env python3
"""
Builds the pixel-art icon sprite into index.html.

  python3 tools/build-pixels.py

- Reads luisacoded/pixels.src.txt (16x16 grids, one letter per colour).
- Adds a 1px ink outline around every filled shape automatically.
- Colours are CSS variables (--d-blue, ...) so each icon has a light
  and a dark version (see styles/doodles.css).
- Injects the sprite between <!-- doodles:start --> / <!-- doodles:end -->,
  using the same #d-NAME ids the page already references.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "luisacoded" / "pixels.src.txt"
HTML = ROOT / "index.html"
SIZE = 16

COLORS = {
    "k": "var(--d-ink)", "K": "#2B3550",
    "w": "var(--d-surface)", "W": "var(--d-white)",
    "b": "var(--d-blue)", "B": "var(--d-blue-2)",
    "y": "var(--d-yellow)", "Y": "var(--d-yellow-2)", "o": "var(--d-orange)",
    "p": "var(--d-pink)", "P": "var(--d-pink-2)",
    "g": "var(--d-green)", "G": "var(--d-green-2)",
    "t": "var(--d-teal)", "E": "var(--d-teal-2)",
    "r": "var(--d-red)", "u": "var(--d-purple)", "U": "var(--d-purple-2)",
    "d": "var(--d-django)", "T": "var(--d-ts)",
    "~": "var(--d-blue-2)", "!": "var(--d-red)", "*": "var(--d-orange)",
}
NO_OUTLINE = set("k~!*.")


def parse(text):
    icons, name, rows = {}, None, []
    for line in text.splitlines():
        if line.startswith("#") or not line.strip():
            continue
        if line.startswith("@"):
            if name:
                icons[name] = rows
            name, rows = line[1:].strip(), []
        else:
            rows.append(line.rstrip("\n"))
    if name:
        icons[name] = rows
    return icons


def outline(rows):
    grid = [list(r.ljust(SIZE, ".")[:SIZE]) for r in rows[:SIZE]]
    grid += [["."] * SIZE for _ in range(SIZE - len(grid))]
    out = [row[:] for row in grid]
    for y in range(SIZE):
        for x in range(SIZE):
            if grid[y][x] != ".":
                continue
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                nx, ny = x + dx, y + dy
                if 0 <= nx < SIZE and 0 <= ny < SIZE and grid[ny][nx] not in NO_OUTLINE:
                    out[y][x] = "k"
                    break
    return out


def to_rects(grid):
    parts = []
    for y, row in enumerate(grid):
        x = 0
        while x < SIZE:
            c = row[x]
            if c == ".":
                x += 1
                continue
            start = x
            while x < SIZE and row[x] == c:
                x += 1
            parts.append(f'<rect x="{start}" y="{y}" width="{x - start}" height="1" style="fill:{COLORS[c]}"/>')
    return "".join(parts)


icons = parse(SRC.read_text())
for name, rows in icons.items():
    bad = [i for i, r in enumerate(rows) if len(r) != SIZE]
    if len(rows) != SIZE or bad:
        raise SystemExit(f"{name}: needs {SIZE} rows of {SIZE} chars (rows {bad}, got {len(rows)} rows)")
    unknown = set("".join(rows)) - set(COLORS) - {"."}
    if unknown:
        raise SystemExit(f"{name}: unknown colour letters {unknown}")

symbols = "\n".join(
    f'<symbol id="d-{n}" viewBox="0 0 {SIZE} {SIZE}"><g style="stroke:none" shape-rendering="crispEdges">'
    f"{to_rects(outline(r))}</g></symbol>"
    for n, r in icons.items()
)

sprite = (
    "<!-- doodles:start (generated by tools/build-pixels.py — edit luisacoded/pixels.src.txt) -->\n"
    '<svg class="doodle-sprite" xmlns="http://www.w3.org/2000/svg" aria-hidden="true" focusable="false">\n'
    f"{symbols}\n</svg>\n<!-- doodles:end -->"
)

html = HTML.read_text()
html = re.sub(r"<!-- doodles:start.*?<!-- doodles:end -->", lambda _: sprite, html, flags=re.S)
HTML.write_text(html)
print(f"{len(icons)} pixel icons:", ", ".join(icons))


# ---- Favicon: the pixel rocket as a standalone SVG ----------------------
# Uses the real colour values from styles/doodles.css and switches to the
# dark palette with the visitor's system theme.
FAVICON_ICON = "rocket"
FAVICON = ROOT / "luisacoded" / "favicon.svg"
css = (ROOT / "styles" / "doodles.css").read_text()


def palette(selector):
    block = re.search(re.escape(selector) + r"\s*\{(.*?)\}", css, re.S).group(1)
    return dict(re.findall(r"--(d-[\w-]+):\s*([^;]+);", block))


light, dark = palette(":root"), {**palette(":root"), **palette('[data-theme="dark"]')}
used = sorted({v[6:-1] for v in COLORS.values() if v.startswith("var(")})
rules = lambda p: "".join(f"--{n}:{p[n]};" for n in used)
icon_svg = to_rects(outline(icons[FAVICON_ICON]))
FAVICON.write_text(
    f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {SIZE} {SIZE}" shape-rendering="crispEdges">'
    f"<style>svg{{{rules(light)}}}@media (prefers-color-scheme: dark){{svg{{{rules(dark)}}}}}</style>"
    f"{icon_svg}</svg>\n"
)
print(f"favicon: {FAVICON.relative_to(ROOT)} ({FAVICON_ICON})")
